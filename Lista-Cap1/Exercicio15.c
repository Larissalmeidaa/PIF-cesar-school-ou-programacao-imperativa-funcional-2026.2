/*Questão 15. A diretiva #include, amplamente utilizada no topo dos arquivos C, 
é classificada como: 
a) Uma instrução C nativa (compilada diretamente em linguagem de máquina). 
b) Uma instrução específica de linguagens de programação orientadas a objetos. 
c) Uma diretiva especial para o pré-processador C, executada antes da compilação. 
d) Um objeto de classe de armazenamento dinâmico na memória heap. 

LETRA C --> #include é uma diretiva de pré-processador. 
            Isso significa que ela não é compilada diretamente em código de máquina 
            — ela é processada antes da fase de compilação propriamente dita, 
            por uma etapa chamada pré-processamento.*/